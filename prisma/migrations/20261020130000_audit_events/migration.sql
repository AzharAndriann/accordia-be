CREATE TYPE "AuditEventType" AS ENUM (
  'PROJECT_CREATED', 'INVITATION_CREATED', 'INVITATION_ACCEPTED',
  'AGREEMENT_DRAFT_CREATED', 'AGREEMENT_UPDATED', 'AGREEMENT_SUBMITTED',
  'AGREEMENT_APPROVED', 'AGREEMENT_ACCEPTED', 'AGREEMENT_REJECTED',
  'CHANGE_REQUEST_CREATED', 'CHANGE_REQUEST_PROPOSED', 'FILE_UPLOADED',
  'DELIVERY_SUBMITTED', 'DELIVERY_ACCEPTED', 'REVISION_REQUESTED',
  'PAYMENT_SUBMITTED', 'PAYMENT_CONFIRMED', 'PAYMENT_REJECTED'
);
CREATE TABLE "AuditEvent" (
    "id" UUID NOT NULL,
    "projectId" UUID NOT NULL,
    "actorId" UUID NOT NULL,
    "type" "AuditEventType" NOT NULL,
    "entityType" VARCHAR(40) NOT NULL,
    "entityId" UUID NOT NULL,
    "metadata" JSONB NOT NULL DEFAULT '{}',
    "serverTime" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "AuditEvent_pkey" PRIMARY KEY ("id")
);
CREATE INDEX "AuditEvent_projectId_serverTime_id_idx" ON "AuditEvent"("projectId", "serverTime", "id");
CREATE INDEX "AuditEvent_actorId_idx" ON "AuditEvent"("actorId");
ALTER TABLE "AuditEvent" ADD CONSTRAINT "AuditEvent_projectId_fkey" FOREIGN KEY ("projectId") REFERENCES "Project"("id") ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE "AuditEvent" ADD CONSTRAINT "AuditEvent_actorId_fkey" FOREIGN KEY ("actorId") REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
